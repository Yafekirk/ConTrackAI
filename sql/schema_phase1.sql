-- -----------------------------------------------------------------------------
-- 3b) In-app notifications (read by api/alerts.php, written by api/config.php)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.alerts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES public.users (id),
  title varchar(200) NOT NULL,
  message text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'unread',
  created_at timestamptz NOT NULL DEFAULT now()
);

-- created_at must be timestamptz, otherwise the browser renders UTC values as local time.
ALTER TABLE public.alerts
  ALTER COLUMN created_at TYPE timestamptz USING (created_at AT TIME ZONE 'UTC'),
  ALTER COLUMN created_at SET DEFAULT now(),
  ALTER COLUMN created_at SET NOT NULL;

ALTER TABLE public.alerts DROP CONSTRAINT IF EXISTS alerts_status_chk;
ALTER TABLE public.alerts ADD CONSTRAINT alerts_status_chk CHECK (status IN ('unread', 'read'));

CREATE INDEX IF NOT EXISTS alerts_user_created_idx ON public.alerts (user_id, created_at DESC);

ALTER TABLE public.alerts ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.alerts IS 'In-app notifications per user. RLS on; PHP service role reads and writes.';

-- -----------------------------------------------------------------------------
