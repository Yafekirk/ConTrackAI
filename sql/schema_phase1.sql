-- -----------------------------------------------------------------------------
-- 5) Signup credential CHECKs (idempotent: drop then add)
--    Password complexity cannot be checked after hashing; only non-empty hash.
-- -----------------------------------------------------------------------------
-- Normalize rows that would fail new CHECKs (spaces in phones, digits in names).
UPDATE public.users
SET contact_number = NULLIF(regexp_replace(btrim(contact_number), '\s+', '', 'g'), '')
WHERE contact_number IS NOT NULL
  AND contact_number IS DISTINCT FROM regexp_replace(btrim(contact_number), '\s+', '', 'g');

UPDATE public.users
SET contact_number = NULL
WHERE contact_number IS NOT NULL
  AND contact_number !~ '^(09[0-9]{9}|\+639[0-9]{9}|639[0-9]{9})$';

UPDATE public.users
SET supplier_type = NULL
WHERE supplier_type IS NOT NULL
  AND supplier_type NOT IN ('Supply', 'Lease', 'Service', 'Other');

UPDATE public.users
SET name = 'User'
WHERE char_length(btrim(name)) < 2
   OR char_length(btrim(name)) > 120
   OR btrim(name) ~ '[[:cntrl:]]';

UPDATE public.users
SET email = lower(btrim(email))
WHERE email IS DISTINCT FROM lower(btrim(email));

ALTER TABLE public.users DROP CONSTRAINT IF EXISTS users_name_format_chk;
ALTER TABLE public.users ADD CONSTRAINT users_name_format_chk CHECK (
  char_length(btrim(name)) BETWEEN 2 AND 120
  AND btrim(name) !~ '[[:cntrl:]]'
);

ALTER TABLE public.users DROP CONSTRAINT IF EXISTS users_company_name_chk;
ALTER TABLE public.users ADD CONSTRAINT users_company_name_chk CHECK (
  company_name IS NULL
  OR (
    char_length(btrim(company_name)) BETWEEN 2 AND 120
    AND btrim(company_name) !~ '[[:cntrl:]]'
  )
);

ALTER TABLE public.users DROP CONSTRAINT IF EXISTS users_email_format_chk;
ALTER TABLE public.users ADD CONSTRAINT users_email_format_chk CHECK (
  char_length(email) <= 254
  AND position('@' IN email) > 1
);

ALTER TABLE public.users DROP CONSTRAINT IF EXISTS users_contact_number_ph_chk;
ALTER TABLE public.users ADD CONSTRAINT users_contact_number_ph_chk CHECK (
  contact_number IS NULL
  OR contact_number ~ '^(09[0-9]{9}|\+639[0-9]{9}|639[0-9]{9})$'
);

ALTER TABLE public.users DROP CONSTRAINT IF EXISTS users_supplier_type_chk;
ALTER TABLE public.users ADD CONSTRAINT users_supplier_type_chk CHECK (
  supplier_type IS NULL
  OR supplier_type IN ('Supply', 'Lease', 'Service', 'Other')
