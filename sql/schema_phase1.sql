-- ConTrack Phase 1 — run in Supabase SQL Editor (PostgreSQL)
-- Creates core tables if missing, then applies additive upgrades (idempotent).
-- Telemetry: last_login_at / last_seen_at updated by PHP on login and heartbeat.

-- -----------------------------------------------------------------------------
-- 1) Core tables (greenfield / empty project)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL DEFAULT '',
  email text NOT NULL,
  password text NOT NULL DEFAULT '',
  role text NOT NULL DEFAULT 'client',
  contact_number text,
  supplier_type text,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz,
  last_seen_at timestamptz,
  is_disabled boolean NOT NULL DEFAULT false,
  CONSTRAINT users_email_unique UNIQUE (email)
);

-- id is uuid: api/contract_pdf.php, nlp_usage.contract_id, and the portal JS all treat
-- contract ids as opaque strings.
CREATE TABLE IF NOT EXISTS public.vendor_contracts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  vendor_id bigint REFERENCES public.users (id) ON DELETE CASCADE,
  vendor_name text,
  contract_title text NOT NULL DEFAULT '',
  contract_type text,
  contract_value numeric,
  start_date date,
  end_date date,
  payment_terms text,
  scope_of_work text,
  status text NOT NULL DEFAULT 'pending',
  uploaded_at timestamptz,
  source_file_name text,
  file_name text,
  file_path text,
  currency text DEFAULT 'PHP',
  reviewed_at timestamptz,
  reviewed_by text,
  ceo_notes text,
  manager_notes text,
  recommended_action text,
  manager_reviewed_at timestamptz,
  manager_reviewed_by bigint REFERENCES public.users (id) ON DELETE SET NULL
);

