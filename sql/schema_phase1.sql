  user_id bigint NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  code_hash text NOT NULL,
  reset_token_hash text,
  attempts integer NOT NULL DEFAULT 0,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_password_resets_user ON public.password_resets (user_id, created_at DESC);

ALTER TABLE public.password_resets ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.password_resets IS 'Hashed email codes and one-time reset tokens. PHP service role only.';

