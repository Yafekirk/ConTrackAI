-- -----------------------------------------------------------------------------
-- 8) Manual vendor scoring (evaluations are stored; scores are never predicted)
--    Vendors are rows in public.users (role vendor/client), not public.vendors.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.vendor_score_criteria (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  code text NOT NULL,
  name text NOT NULL,
  description text,
  weight numeric(6,4) NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT vendor_score_criteria_code_unique UNIQUE (code),
  CONSTRAINT vendor_score_criteria_weight_chk CHECK (weight > 0 AND weight <= 1),
  CONSTRAINT vendor_score_criteria_code_chk CHECK (code ~ '^[a-z][a-z0-9_]{1,40}$')
);

CREATE TABLE IF NOT EXISTS public.vendor_evaluations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  vendor_id integer NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  evaluator_id integer NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT,
  evaluated_at timestamptz NOT NULL DEFAULT now(),
  overall_score numeric(6,2) NOT NULL,
  rating text NOT NULL,
  remarks text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT vendor_evaluations_score_chk CHECK (overall_score >= 0 AND overall_score <= 100),
  CONSTRAINT vendor_evaluations_rating_chk CHECK (
    rating IN ('excellent', 'good', 'satisfactory', 'needs_improvement')
  ),
  CONSTRAINT vendor_evaluations_remarks_chk CHECK (remarks IS NULL OR char_length(remarks) <= 2000)
);

CREATE TABLE IF NOT EXISTS public.vendor_evaluation_scores (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  evaluation_id uuid NOT NULL REFERENCES public.vendor_evaluations (id) ON DELETE CASCADE,
  criterion_id bigint NOT NULL REFERENCES public.vendor_score_criteria (id) ON DELETE RESTRICT,
  score numeric(6,2) NOT NULL,
  weighted_score numeric(8,4) NOT NULL,
  CONSTRAINT vendor_evaluation_scores_unique UNIQUE (evaluation_id, criterion_id),
  CONSTRAINT vendor_evaluation_scores_score_chk CHECK (score >= 0 AND score <= 100)
);

CREATE INDEX IF NOT EXISTS vendor_evaluations_vendor_evaluated_idx
  ON public.vendor_evaluations (vendor_id, evaluated_at DESC);
CREATE INDEX IF NOT EXISTS vendor_evaluations_evaluator_idx
  ON public.vendor_evaluations (evaluator_id);

ALTER TABLE public.vendor_score_criteria ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vendor_evaluations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vendor_evaluation_scores ENABLE ROW LEVEL SECURITY;

