-- -----------------------------------------------------------------------------
-- 7) AI / NLP usage log (extract + submit)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.nlp_usage (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id integer REFERENCES public.users (id) ON DELETE SET NULL,
  contract_id uuid REFERENCES public.vendor_contracts (id) ON DELETE SET NULL,
  source text NOT NULL,
  engine text NOT NULL,
  success boolean NOT NULL DEFAULT true,
  duration_ms integer,
  source_file_name text,
  input_kind text,
  input_chars integer,
  fields_filled jsonb NOT NULL DEFAULT '[]'::jsonb,
  clause_count integer NOT NULL DEFAULT 0,
  avg_confidence numeric(6,4),
  error_message text,
  ip_address text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT nlp_usage_source_chk CHECK (source IN ('extract', 'submit')),
  CONSTRAINT nlp_usage_engine_chk CHECK (engine IN ('python-ml', 'php-regex', 'unavailable')),
  CONSTRAINT nlp_usage_input_kind_chk CHECK (
    input_kind IS NULL OR input_kind IN ('pdf', 'text', 'pdf_and_text')
  )
);

CREATE INDEX IF NOT EXISTS nlp_usage_user_id_idx ON public.nlp_usage (user_id);
CREATE INDEX IF NOT EXISTS nlp_usage_contract_id_idx ON public.nlp_usage (contract_id);
CREATE INDEX IF NOT EXISTS nlp_usage_created_at_idx ON public.nlp_usage (created_at DESC);
CREATE INDEX IF NOT EXISTS nlp_usage_engine_idx ON public.nlp_usage (engine);

ALTER TABLE public.nlp_usage ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.nlp_usage IS 'AI/NLP extraction usage: who ran it, which engine, duration, and which fields were filled. Written by the PHP API with the service role.';

